"""Шаг 1. Данные из Excel → слои «почва_трава», «вода», «молоко» в базе.

Откуда берутся данные:
  исходные_данные/Данные_019.xlsx – главный файл проекта (его правите вы):
    лист «выезды»     – список выездов по порядку;
    лист «точки»      – координаты точек отбора (почва и травостой, вода);
    лист «почва»      – агрохимия, влажность и плотность по горизонтам;
    лист «травостой»  – высота, покрытие, деградация, урожайность, виды, питательность;
    лист «вода»       – EC, TDS, E. coli, колиформы, pH, мутность, температура, оценка;
    лист «молоко»     – пробы молока со своими координатами.
  В листах анализов одна строка = одна точка в одном выезде.

Что делает:
  1) Читает точки и анализы, связывает их по ключу «округ + номер ТС»
     (например «Карасуский_ТС1»).
  2) Для каждого выезда собирает строку на каждую точку. Если показатель в этом выезде
     не определялся, ячейка остаётся пустой.
  3) Проверяет: нет повторов, нет точек, которых нет в листе «точки», нет неизвестных выездов.
  4) Сохраняет слои в база/База_019.gpkg. В каждом слое есть столбец «выезд»:
     в QGIS выезд выбирается фильтром (правый клик по слою → Фильтр…).
"""
import pandas as pd
import geopandas as gpd
from общее import *

ВЫЕЗДЫ = [v['id'] for v in выезды()]
ОБЩИЕ = {'Сельский округ': 'округ', 'ТС': 'тс', 'Выезд': 'выезд', 'Дата отбора': 'дата'}


def проверить_выезды(df, лист):
    df['выезд'] = df.выезд.astype(str).str.strip()
    чужие = sorted(set(df.выезд) - set(ВЫЕЗДЫ))
    assert not чужие, f'в листе «{лист}» выезды {чужие} не записаны в листе «выезды»'


def прочитать(лист, столбцы):
    """Лист Excel → таблица с внутренними именами столбцов и ключом точки."""
    df = pd.read_excel(ДАННЫЕ, sheet_name=лист)
    df = df.rename(columns={**ОБЩИЕ, **{v: k for k, v in столбцы.items()}})
    нет = [k for k in столбцы if k not in df.columns]
    assert not нет, f'в листе «{лист}» нет столбцов: {[столбцы[k] for k in нет]}'
    df = df.dropna(subset=['округ', 'тс'])
    df['округ'] = df.округ.astype(str).str.strip().apply(округ)
    df['тс'] = df.тс.astype(int)
    df['ключ'] = df.округ + '_ТС' + df.тс.astype(str)
    проверить_выезды(df, лист)
    df['дата'] = df.дата.apply(lambda v: None if pd.isna(v) else
                               (v.strftime('%d.%m.%Y') if hasattr(v, 'strftime') else str(v).strip()))
    for k in столбцы:                       # все числа – дробные (10 → 10.0), как в QGIS
        if pd.api.types.is_numeric_dtype(df[k]):
            df[k] = df[k].astype(float)
    дубли = df[df.duplicated(['ключ', 'выезд'], keep=False)]
    assert дубли.empty, f'в листе «{лист}» повторяются строки: {sorted(set(дубли.ключ + " / " + дубли.выезд))}'
    return df[['ключ', 'выезд', 'дата'] + list(столбцы)]


# ---------- 1. Точки ----------
T = pd.read_excel(ДАННЫЕ, sheet_name='точки')
T = T.rename(columns={'Сельский округ': 'округ', 'ТС': 'тс', 'Тип': 'тип', 'Источник воды': 'источник',
                      'Широта': 'lat', 'Долгота': 'lon', 'Откуда координаты': 'коорд_источник',
                      'Примечание': 'примечание'})
T['округ'] = T.округ.apply(округ)
T['тс'] = T.тс.astype(int)
T['ключ'] = T.округ + '_ТС' + T.тс.astype(str)
дубли = T[T.duplicated(['тип', 'ключ'], keep=False)]
assert дубли.empty, f'в листе «точки» повторяются точки: {sorted(set(дубли.ключ))}'


def по_выездам(тип, листы):
    """Точки типа × выезды, в которых есть хоть один из листов; анализы присоединены."""
    t = T[T.тип == тип][['округ', 'тс', 'ключ', 'источник', 'примечание', 'lon', 'lat', 'коорд_источник']]
    таблицы = []
    for лист, столбцы in листы:
        таб = прочитать(лист, столбцы)
        лишние = set(таб.ключ) - set(t.ключ)
        assert not лишние, f'в листе «{лист}» есть точки, которых нет в листе «точки»: {sorted(лишние)}'
        таблицы.append(таб)
    есть = sorted({в for таб in таблицы for в in таб.выезд}, key=ВЫЕЗДЫ.index)
    out = pd.concat([t.assign(выезд=в) for в in есть], ignore_index=True)
    out['дата'] = None
    for таб in таблицы:
        out = out.merge(таб.rename(columns={'дата': 'дата_'}), on=['ключ', 'выезд'], how='left')
        out['дата'] = out.дата.fillna(out.pop('дата_'))
    return out


P = по_выездам('почва и травостой', [('почва', ПОЧВА), ('травостой', ТРАВОСТОЙ)]).drop(columns=['источник', 'примечание'])
W = по_выездам('вода', [('вода', ВОДА)])

# ---------- 2. Молоко: координаты прямо в листе ----------
M = pd.read_excel(ДАННЫЕ, sheet_name='молоко')
M = M.rename(columns={**ОБЩИЕ, 'Проба': 'проба', 'Место отбора': 'место', 'Широта': 'lat', 'Долгота': 'lon',
                      'Откуда координаты': 'коорд_источник', 'Примечание': 'примечание',
                      **{v: k for k, v in МОЛОКО.items()}})
M = M.dropna(subset=['выезд'])
проверить_выезды(M, 'молоко')
M['проба'] = M.проба.astype(str).str.replace(r'\.0$', '', regex=True)
дубли = M[M.duplicated(['выезд', 'проба'], keep=False)]
assert дубли.empty, f'в листе «молоко» повторяются пробы: {sorted(set(дубли.выезд + " № " + дубли.проба))}'
M['округ'] = M.округ.apply(lambda v: None if pd.isna(v) else округ(str(v)))
for k in МОЛОКО:
    M[k] = M[k].astype(float)
M = M[M.lat.notna() & M.lon.notna()]   # на карту – только пробы с координатами


# ---------- 3. Общие поля и запись в базу ----------
def оформить(df, точки=True):
    df = df.copy()
    if точки:
        df = df.drop(columns='ключ')
        df.insert(1, 'нп', df.округ.map(ОКРУГА))
        df.insert(3, 'тс_код', 'ТС#' + df.тс.astype(str))
        df.insert(4, 'ключ', df.округ + '_ТС' + df.тс.astype(str))
    в = df.pop('выезд'); df.insert(0, 'выезд', в)
    df['долгота'] = df.lon.round(6)
    df['широта'] = df.lat.round(6)
    к = df.pop('коорд_источник'); df['коорд_источник'] = к
    g = gpd.GeoDataFrame(df.drop(columns=['lon', 'lat']),
                         geometry=gpd.points_from_xy(df.lon, df.lat), crs=4326)
    g['_в'] = g.выезд.map(ВЫЕЗДЫ.index)
    return g.to_crs(CRS).sort_values(['_в'] + (['округ', 'тс'] if точки else ['проба'])).drop(columns='_в')


БАЗА.parent.mkdir(exist_ok=True)
if БАЗА.exists():
    БАЗА.unlink()
оформить(P).to_file(БАЗА, layer='почва_трава', driver='GPKG')
оформить(W).to_file(БАЗА, layer='вода', driver='GPKG')
оформить(M, точки=False).to_file(БАЗА, layer='молоко', driver='GPKG')
итог = ', '.join(f'{в}: почва {(P.выезд == в).sum()}, вода {(W.выезд == в).sum()}, молоко {(M.выезд == в).sum()}'
                 for в in ВЫЕЗДЫ)
print(f'Шаг 1 готов → {БАЗА.name}. {итог}')
