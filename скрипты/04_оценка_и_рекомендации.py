def species(dom,sub):
    dom=dom if isinstance(dom,str) else ''; sub=sub if isinstance(sub,str) else ''
    if not dom: return dict(text='',sev=None,good=[],weeds=[])
    t=(dom+', '+sub).lower()
    g=sorted({s for s in GOOD if s in t}); b=sorted({s for s in WEED if s in t}); pol='полын' in dom.lower()
    if pol and not any(s in dom.lower() for s in ['типчак','ковыль','пырей']): q=('Полынь доминирует – признак сбоя пастбища',2)
    elif b and any(s in dom.lower() for s in ['марь','подорожник','горец']): q=('Сорно-рудеральные виды в доминантах – признак перевыпаса',3)
