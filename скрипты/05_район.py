ОКР = sorted(ОКРУГА)


def лист(имя):
    df = pd.read_excel(РАЙОН, sheet_name=имя)
    df = df.dropna(how='all')
    if 'Сельский округ' in df:
        bad = sorted(set(df['Сельский округ'].dropna()) - set(ОКРУГА))
        if bad:
            raise SystemExit(f'Район_019.xlsx, лист «{имя}»: неизвестный округ {bad}. Названия – как в листе «округа».')
    return df


def ч(v):
    if v is None or (isinstance(v, numbers.Number) and math.isnan(v)):
        return None
    if isinstance(v, numbers.Number):
        return int(v) if float(v).is_integer() else round(float(v), 4)
    return str(v)


def записи(df):
    return [{k: ч(v) for k, v in r.items()} for r in df.to_dict('records')]


