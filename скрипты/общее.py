def округ(текст):
    """«Бидаик», «Аккудук», «Кишенеколь 1» → официальное название округа."""
    s = текст.lower().strip()
    for k in sorted(_НАЧАЛА, key=len, reverse=True):
        if s.startswith(k):
            return _НАЧАЛА[k]
    raise ValueError(f'Не узнаю округ: {текст!r}')


def число(s):
    """'3,2' → 3.2; 'менее 5,0' → 5.0; '' → None"""
    if s in ('', None):
        return None
    return float(str(s).replace(',', '.').replace('менее', '').strip())


def таблицы_docx(путь):
    """Все таблицы документа Word как списки строк (текст ячеек)."""
    import zipfile
    x = zipfile.ZipFile(путь).read('word/document.xml').decode()
    out = []
    for t in re.findall(r'<w:tbl>.*?</w:tbl>', x, re.S):
        rows = []
        for r in re.findall(r'<w:tr[ >].*?</w:tr>', t, re.S):
            rows.append([re.sub(r'<[^>]+>', '', c).strip()
                         for c in re.findall(r'<w:tc>.*?</w:tc>', r, re.S)])
        out.append(rows)
    return out
